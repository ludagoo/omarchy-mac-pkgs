#!/usr/bin/env python3
"""Offline tests for smartroom-release: no ESP, no btrfs, no reboot, a fake clock.

A fake `btrfs` (test/fake-btrfs) stands in for the real one on directories, so
the stage, arm, health, mark-good and rollback paths run end to end.
"""
import contextlib
import hashlib
import importlib.machinery
import importlib.util
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
TOOL = HERE.parent / "bin" / "smartroom-release"

loader = importlib.machinery.SourceFileLoader("smartroom_release", str(TOOL))
spec = importlib.util.spec_from_loader("smartroom_release", loader)
sr = importlib.util.module_from_spec(spec)
loader.exec_module(sr)

LIMINE = """\
timeout: 1
quiet: yes
default_entry: 2
hash_mismatch_panic: no

/+SmartRoom Firmware
comment: machine-id=e4c6
### This OS entry is auto-generated by limine-entry-tool
comment: SmartRoom Firmware
  //linux-aurora
  comment: Kernel version: 7.3.0-0sredge3-1-ARCH
  protocol: efi
  path: boot():/EFI/Linux/omarchy_linux-aurora.efi
  cmdline: root=UUID=4f4d rw rootflags=subvol=@,x-systemd.device-timeout=0 quiet panic=10
"""
CMDLINE = "root=UUID=4f4d rw rootflags=subvol=@,x-systemd.device-timeout=0 quiet panic=10"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class FakeHost(sr.Host):
    """A Host whose paths are under a temp prefix and whose clock is fake."""

    def __init__(self, prefix):
        super().__init__(prefix)
        self.clock = 1000.0
        self.reboots = 0
        self.hard = 0
        self.connected = True
        self.network = True
        self.screens = 3
        self.oneshot = None
        self.saved = None
        self.save_works = True
        self.dog_writes = []
        self.health_log = []

    def now(self):
        return self.clock

    def monotonic(self):
        return self.clock

    def sleep(self, seconds):
        self.clock += seconds

    def agent_connected(self):
        return self.connected

    def network_up(self):
        return self.network

    def displays(self):
        return self.screens

    def set_oneshot(self, entry_id):
        self.oneshot = entry_id

    def save_efi_vars(self):
        if self.save_works:
            self.saved = self.oneshot

    def oneshot_saved(self):
        return self.saved is not None and self.saved == self.oneshot

    def reboot(self):
        self.reboots += 1

    def hard_reboot(self):
        self.hard += 1

    @contextlib.contextmanager
    def top(self):
        top = self.p("/top")
        top.mkdir(parents=True, exist_ok=True)
        yield top

    def efivar(self, name):
        return self.p("/sys/firmware/efi/efivars") / name


class World:
    """One room: ESP, running root, a release directory."""

    def __init__(self, test):
        self.tmp = Path(tempfile.mkdtemp(prefix="srel-"))
        test.addCleanup(shutil.rmtree, self.tmp, True)
        self.prefix = self.tmp / "room"
        self.host = FakeHost(str(self.prefix))
        self.esp = self.prefix / "boot/efi"
        self.test = test
        self.bin = self.tmp / "bin"
        self.bin.mkdir()
        shim = self.bin / "btrfs"
        shim.write_text((HERE / "fake-btrfs").read_text())
        shim.chmod(0o755)
        env = mock.patch.dict(os.environ, {"PATH": f"{self.bin}:{os.environ['PATH']}"})
        env.start()
        test.addCleanup(env.stop)
        self.build_room()

    def build_room(self):
        p = self.prefix
        (self.esp / "m1n1").mkdir(parents=True)
        (self.esp / "EFI/Linux").mkdir(parents=True)
        (self.esp / "limine.conf").write_text(LIMINE)
        (self.esp / "m1n1/boot.bin").write_bytes(b"stage2-installed")
        (self.esp / "EFI/Linux/omarchy_linux-aurora.efi").write_bytes(b"uki-installed")
        (p / "proc/sys/kernel/random").mkdir(parents=True)
        (p / "proc/sys/kernel/random/boot_id").write_text("boot-1\n")
        (p / "proc/cmdline").write_text(CMDLINE + "\n")
        (p / "proc/uptime").write_text("100.0 100.0\n")
        (p / "dev").mkdir()
        (p / "dev/watchdog").write_text("")
        root = p / "top/@"
        (root / "etc/default").mkdir(parents=True)
        (root / "etc/fstab").write_text(
            "UUID=aa  /  btrfs  noatime,subvol=@  0 0\nUUID=aa  /home  btrfs  noatime,subvol=@home  0 0\n")
        (root / "etc/default/limine").write_text(
            f'TARGET_OS_NAME="SmartRoom Firmware"\nKERNEL_CMDLINE[default]="{CMDLINE}"\n')
        # the room's own files, in the running root (which is the prefix itself)
        for rel, data in {
            "etc/machine-id": "machine-A\n", "etc/hostname": "room-A\n",
            "etc/ssh/ssh_host_ed25519_key": "HOSTKEY-A", "etc/ssh/ssh_host_ed25519_key.pub": "HOSTPUB-A",
            "etc/smartroomos/unique-id": "uid-A\n", "var/lib/smartroomos/studio-firstboot.done": "done\n",
            "opt/smartroom/config/agent.json": '{"serverUrl": "https://s.example"}',
            "opt/smartroom/state/requirements.sha256": "abc\n",
        }.items():
            f = p / rel
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(data)

    # a release directory -------------------------------------------------
    def release(self, name="2026.11.21-1", cmdline=CMDLINE, uki=b"uki-new", stage2=b"stage2-new", pad=0):
        d = self.tmp / f"release-{name}"
        (d / "m1n1").mkdir(parents=True)
        (d / "EFI/Linux").mkdir(parents=True)
        (d / "m1n1/boot.bin").write_bytes(stage2)
        (d / "EFI/Linux/omarchy_linux-aurora.efi").write_bytes(uki)
        tree = self.tmp / f"tree-{name}"
        root = tree / "factory"
        (root / "etc/default").mkdir(parents=True)
        (root / "etc/fstab").write_text("UUID=aa  /  btrfs  noatime,subvol=@  0 0\n")
        (root / "etc/default/limine").write_text(f'KERNEL_CMDLINE[default]="{cmdline}"\n')
        (root / "etc/machine-id").write_text("machine-RELEASE\n")
        (root / "etc/hostname").write_text("release-default\n")
        (root / "usr/lib").mkdir(parents=True)
        (root / "usr/lib/marker").write_text(f"release {name}\n")
        tar = subprocess.run(["tar", "-C", str(tree), "-cf", "-", "factory"], capture_output=True, check=True).stdout
        stream = subprocess.run(["zstd", "-q", "-c"], input=tar, capture_output=True, check=True).stdout
        (d / "root.btrfs.zst").write_bytes(stream)
        manifest = {
            "schema": 1, "id": name, "created": "2026-11-21T00:00:00Z", "parent": None,
            "root": {"file": "root.btrfs.zst", "sha256": sha(stream), "size": len(stream)},
            "boot": [
                {"role": "stage2", "path": "m1n1/boot.bin", "sha256": sha(stage2), "size": len(stage2) + pad},
                {"role": "uki", "path": "EFI/Linux/omarchy_linux-aurora.efi", "sha256": sha(uki), "size": len(uki)},
            ],
        }
        (d / "manifest.json").write_text(json.dumps(manifest))
        return d

    def state(self):
        return json.loads((self.esp / "smartroom-release/state.json").read_text())

    def limine(self):
        return (self.esp / "limine.conf").read_text()

    def trial_boot(self, name="2026.11.21-1"):
        """Reboot into the armed trial: aura spent the marker, Limine took the one-shot."""
        marker = self.esp / "aura-try"
        marker.write_bytes(marker.read_bytes().replace(b"armed", b"spent", 1))
        (self.prefix / "proc/cmdline").write_text(sr.trial_cmdline(CMDLINE, f"@r-{name}", name) + "\n")
        (self.prefix / "proc/sys/kernel/random/boot_id").write_text("boot-2\n")
        trial_path = self.prefix / "proc/device-tree/chosen/aurora,trial"
        trial_path.parent.mkdir(parents=True, exist_ok=True)
        trial_path.write_bytes(sr.TRIAL_BOOT.encode() + b"\0")
        self.host.oneshot = None
        self.host.saved = None

    def back_on_configured(self, root="@", boot_id="boot-3"):
        (self.prefix / "proc/cmdline").write_text(sr.with_subvol(CMDLINE, root, None) + "\n")
        (self.prefix / "proc/sys/kernel/random/boot_id").write_text(boot_id + "\n")
        with contextlib.suppress(FileNotFoundError):
            (self.prefix / "proc/device-tree/chosen/aurora,trial").unlink()

    def run(self, *argv):
        out = io.StringIO()
        err = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = sr.main(["--prefix", str(self.prefix), *argv], host=self.host)
        return code, out.getvalue(), err.getvalue()


class LimineText(unittest.TestCase):
    def test_trial_entry_is_added_beside_the_kernel_entry_and_removed_again(self):
        trial_cmd = sr.trial_cmdline(CMDLINE, "@r-x", "x")
        text = sr.with_trial_entry(LIMINE, "x", sr.TRIAL_UKI, trial_cmd)
        self.assertIn("/SmartRoom Release Trial\n", text)
        self.assertIn(f"path: boot():/{sr.TRIAL_UKI}", text)
        self.assertIn("rootflags=subvol=@r-x,x-systemd.device-timeout=0", text)
        self.assertIn("watchdog.handle_boot_enabled=0", text)
        self.assertIn("smartroom.release=x", text)
        self.assertIn("path: boot():/EFI/Linux/omarchy_linux-aurora.efi", text)  # configured entry untouched
        again = sr.with_trial_entry(text, "y", sr.TRIAL_UKI, sr.trial_cmdline(CMDLINE, "@r-y", "y"))
        self.assertEqual(again.count("/SmartRoom Release Trial"), 1)
        self.assertEqual(sr.strip_trial_entry(text), LIMINE)
        self.assertEqual(sr.strip_trial_entry(LIMINE), LIMINE)

    def test_the_kernel_entry_is_read_and_rewritten_without_the_trial_entry(self):
        text = sr.with_trial_entry(LIMINE, "x", sr.TRIAL_UKI, sr.trial_cmdline(CMDLINE, "@r-x", "x"))
        self.assertEqual(sr.kernel_entry(text)[0], "boot():/EFI/Linux/omarchy_linux-aurora.efi")
        out = sr.set_kernel_entry(text, "EFI/Linux/other.efi", "root=x panic=10")
        self.assertIn("path: boot():/EFI/Linux/other.efi", out)
        self.assertIn("cmdline: root=x panic=10", out)
        self.assertIn("watchdog.handle_boot_enabled=0", out)  # the trial entry is not the kernel entry
        with self.assertRaises(sr.Fail):
            sr.set_kernel_entry("timeout: 1\n", "x", "y")

    def test_subvolume_in_cmdline(self):
        self.assertEqual(sr.with_subvol(CMDLINE, "@r-x", "x"),
                         "root=UUID=4f4d rw rootflags=subvol=@r-x,x-systemd.device-timeout=0 quiet panic=10 smartroom.release=x")
        self.assertEqual(sr.with_subvol("root=a rw panic=10", "@", None), "root=a rw panic=10 rootflags=subvol=@")
        trial = sr.trial_cmdline(CMDLINE, "@r-x", "x")
        self.assertTrue(trial.endswith("watchdog.handle_boot_enabled=0"))
        # promotion strips the trial-only parameter and keeps the release
        self.assertNotIn("watchdog", sr.with_subvol(trial, "@r-x", "x"))
        self.assertEqual(sr.with_subvol(trial, "@r-x", "x").count("smartroom.release"), 1)

    def test_panic_10_is_required(self):
        sr.require_zero_touch(CMDLINE)
        for bad in ("root=a rw", "root=a panic=100", "root=a panic=0", "root=a xpanic=10"):
            with self.assertRaises(sr.Fail):
                sr.require_zero_touch(bad)

    def test_running_root_reads_rootflags(self):
        with tempfile.TemporaryDirectory() as tmp:
            host = FakeHost(tmp)
            (Path(tmp) / "proc").mkdir()
            for line, want in [("root=a rootflags=subvol=@,x=1 panic=10", "@"),
                               ("root=a rootflags=x=1,subvol=/@r-1 panic=10", "@r-1"),
                               ("root=a ro", "@")]:
                (Path(tmp) / "proc/cmdline").write_text(line)
                self.assertEqual(sr.running_root(host), want)


class Window(unittest.TestCase):
    def window(self, rows, now, quiet=300, limit=900):
        return sr.healthy_window(rows, 0, now, quiet, limit)

    def test_five_quiet_minutes_inside_fifteen(self):
        ok = (1, 1, 1)
        rows = [(t, ok) for t in range(0, 400, 5)]
        self.assertTrue(self.window(rows, 400))
        self.assertFalse(self.window([(t, ok) for t in range(0, 295, 5)], 295))
        bad = [(t, ok if t != 150 else (0, 1, 1)) for t in range(0, 400, 5)]
        self.assertFalse(self.window(bad, 400))                       # a gap resets the stretch
        late = [(t, ok if t >= 700 else (0, 1, 1)) for t in range(0, 1100, 5)]
        self.assertFalse(self.window(late, 1100))                     # a window ending after 15 minutes
        self.assertTrue(self.window([(t, ok if t >= 500 else (0, 1, 1)) for t in range(0, 1100, 5)], 1100))
        for lacking in ((1, 0, 1), (1, 1, 0), (0, 1, 1)):
            self.assertFalse(self.window([(t, lacking) for t in range(0, 900, 5)], 900))


class Stage(unittest.TestCase):
    def setUp(self):
        self.w = World(self)

    def stage(self, **kw):
        d = self.w.release(**kw)
        return d, self.w.run("stage", str(d), "--unsigned")

    def test_stage_writes_the_release_beside_the_configured_one(self):
        d, (code, out, err) = self.stage()
        self.assertEqual(code, 0, err)
        top = self.w.prefix / "top"
        new = top / "@r-2026.11.21-1"
        self.assertEqual((new / "usr/lib/marker").read_text(), "release 2026.11.21-1\n")
        # the room's own identity came across, the release's defaults did not win
        self.assertEqual((new / "etc/machine-id").read_text(), "machine-A\n")
        self.assertEqual((new / "etc/hostname").read_text(), "room-A\n")
        self.assertEqual((new / "etc/ssh/ssh_host_ed25519_key").read_text(), "HOSTKEY-A")
        self.assertEqual((new / "var/lib/smartroomos/studio-firstboot.done").read_text(), "done\n")
        self.assertEqual((new / "opt/smartroom/config/agent.json").read_text(), '{"serverUrl": "https://s.example"}')
        # the new root names itself
        self.assertIn("subvol=@r-2026.11.21-1", (new / "etc/fstab").read_text())
        self.assertNotIn("subvol=@ ", (new / "etc/fstab").read_text().splitlines()[0])
        self.assertIn("rootflags=subvol=@r-2026.11.21-1", (new / "etc/default/limine").read_text())
        self.assertEqual((new / "usr/share/smartroomos/release-id").read_text(), "2026.11.21-1\n")
        # the running root is untouched
        self.assertIn("subvol=@ ", (top / "@/etc/fstab").read_text())
        # the boot files sit beside the configured ones, which are byte-identical
        self.assertEqual((self.w.esp / sr.TRIAL_BOOT).read_bytes(), b"stage2-new")
        self.assertEqual((self.w.esp / sr.TRIAL_UKI).read_bytes(), b"uki-new")
        self.assertEqual((self.w.esp / "m1n1/boot.bin").read_bytes(), b"stage2-installed")
        self.assertEqual((self.w.esp / sr.CONFIGURED_UKI).read_bytes(), b"uki-installed")
        # limine has the trial entry; nothing is armed
        self.assertIn(f"path: boot():/{sr.TRIAL_UKI}", self.w.limine())
        self.assertFalse((self.w.esp / "aura-try").exists())
        self.assertIsNone(self.w.host.oneshot)
        st = self.w.state()
        self.assertEqual(st["trial"]["phase"], "staged")
        self.assertEqual(st["trial"]["root"], "@r-2026.11.21-1")
        self.assertEqual(st["configured"]["release"], "installed")
        self.assertFalse(list(self.w.esp.rglob("*.new")))

    def test_a_bad_release_is_refused_before_anything_is_written(self):
        for label, mutate in [
            ("checksum", lambda d: (d / "m1n1/boot.bin").write_bytes(b"tampered")),
            ("missing", lambda d: (d / "root.btrfs.zst").unlink()),
            ("root checksum", lambda d: (d / "root.btrfs.zst").write_bytes(b"x")),
        ]:
            with self.subTest(label):
                d = self.w.release(name=f"r-{label}".replace(" ", "-"))
                mutate(d)
                code, out, err = self.w.run("stage", str(d), "--unsigned")
                self.assertEqual(code, 1, err)
                self.assertFalse((self.w.esp / sr.TRIAL_BOOT).exists())
                self.assertFalse((self.w.esp / sr.TRIAL_UKI).exists())
                self.assertNotIn("Release Trial", self.w.limine())
                self.assertFalse(list((self.w.prefix / "top").glob("@r-*")))

    def test_a_release_without_panic_10_is_refused(self):
        d = self.w.release(cmdline="root=UUID=4f4d rw rootflags=subvol=@ quiet")
        code, out, err = self.w.run("stage", str(d), "--unsigned")
        self.assertEqual(code, 1)
        self.assertIn("panic=10", err)
        self.assertFalse((self.w.esp / sr.TRIAL_UKI).exists())
        self.assertNotIn("Release Trial", self.w.limine())

    def test_manifest_paths_must_stay_inside_the_release(self):
        d = self.w.release()
        m = json.loads((d / "manifest.json").read_text())
        m["boot"][0]["path"] = "../escape"
        (d / "manifest.json").write_text(json.dumps(m))
        code, _, err = self.w.run("stage", str(d), "--unsigned")
        self.assertEqual(code, 1)
        self.assertIn("unsafe", err)
        m["boot"][0]["path"] = "/etc/passwd"
        (d / "manifest.json").write_text(json.dumps(m))
        self.assertEqual(self.w.run("stage", str(d), "--unsigned")[0], 1)

    def test_an_unhealthy_room_is_not_updated(self):
        d = self.w.release()
        self.w.host.connected = False
        code, _, err = self.w.run("stage", str(d), "--unsigned")
        self.assertEqual(code, 1)
        self.assertIn("not healthy", err)
        self.assertFalse((self.w.esp / sr.TRIAL_UKI).exists())

    def test_the_esp_must_have_room_for_the_trial_files(self):
        d = self.w.release(pad=10 * 2**20)
        real = shutil.disk_usage
        with mock.patch.object(shutil, "disk_usage", lambda p: real(p)._replace(free=20 * 2**20)):
            code, _, err = self.w.run("stage", str(d), "--unsigned")
        self.assertEqual(code, 1)
        self.assertIn("ESP", err)
        self.assertFalse((self.w.esp / sr.TRIAL_UKI).exists())

    def test_a_signature_is_required_unless_asked_not_to(self):
        d = self.w.release()
        code, _, err = self.w.run("stage", str(d))
        self.assertEqual(code, 1)
        self.assertIn("keyring", err)
        # a real gpg key
        home = self.w.tmp / "gnupg"
        home.mkdir(mode=0o700)
        env = dict(os.environ, GNUPGHOME=str(home))
        subprocess.run(["gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "", "--quick-generate-key",
                        "release-test <r@example>", "ed25519", "sign", "1d"], env=env, check=True, capture_output=True)
        fpr = subprocess.run(["gpg", "--list-keys", "--with-colons"], env=env, capture_output=True, text=True,
                             check=True).stdout
        fpr = [l.split(":")[9] for l in fpr.splitlines() if l.startswith("fpr")][0]
        keyring = self.w.prefix / "usr/share/smartroomos/release-keyring.gpg"
        keyring.parent.mkdir(parents=True)
        keyring.write_bytes(subprocess.run(["gpg", "--export", fpr], env=env, check=True, capture_output=True).stdout)
        self.assertEqual(self.w.run("stage", str(d))[0], 1)         # keyring but no signature
        subprocess.run(["gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "", "--detach-sign",
                        "--local-user", fpr, "--output", str(d / "manifest.json.sig"), str(d / "manifest.json")],
                       env=env, check=True, capture_output=True)
        code, _, err = self.w.run("stage", str(d))
        self.assertEqual(code, 0, err)
        self.assertTrue(self.w.state()["trial"]["signed"])
        self.w.run("discard")
        m = json.loads((d / "manifest.json").read_text())
        m["id"] = "other"
        (d / "manifest.json").write_text(json.dumps(m))               # the signature no longer matches
        code, _, err = self.w.run("stage", str(d))
        self.assertEqual(code, 1)
        self.assertIn("signature", err)

    def test_an_https_url_is_required_for_a_download(self):
        code, _, err = self.w.run("stage", "http://example.com/r", "--unsigned")
        self.assertEqual(code, 1)
        self.assertIn("https", err)

    def test_the_same_release_is_not_installed_twice(self):
        d = self.w.release()
